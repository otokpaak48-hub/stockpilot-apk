#!/usr/bin/env python3
"""
StockPilot — Full Access PIN Generator
======================================
Generates 50 six-digit Full Access PINs and:
  1. Writes plaintext PINs to download/full_access_pins.txt (gitignored)
  2. Updates lib/pin-data.ts with SHA-256 hashes + salt
"""

import secrets
import hashlib
from pathlib import Path

ROOT     = Path(__file__).resolve().parent.parent
DOWNLOAD = ROOT / "download"
PIN_TS   = ROOT / "lib" / "pin-data.ts"
PINS_FILE = DOWNLOAD / "full_access_pins.txt"

def gen_pin() -> str:
    # 6-digit PIN, no leading zero for readability
    return f"{secrets.randbelow(900000) + 100000}"

def gen_salt() -> str:
    return secrets.token_hex(16)

def sha256_with_salt(text: str, salt: str) -> str:
    return hashlib.sha256((salt + text + salt).encode()).hexdigest()

def main():
    DOWNLOAD.mkdir(parents=True, exist_ok=True)

    pins = [gen_pin() for _ in range(50)]
    salt = gen_salt()
    hashes = [sha256_with_salt(p, salt) for p in pins]

    with open(PINS_FILE, "w") as f:
        f.write("# StockPilot — Full Access PINs (PRIVATE — DO NOT COMMIT)\n")
        f.write("# Generated by scripts/generate_full_access_pins.py\n")
        f.write("# Each PIN unlocks ONE device permanently after the 90-day trial.\n\n")
        for i, p in enumerate(pins, 1):
            f.write(f"{i:2d}. {p}\n")
    print(f"[OK] Wrote 50 plaintext PINs → {PINS_FILE}")
    print(f"     (BACK THIS UP SECURELY — losing it means customers can't unlock!)")

    hash_lines = "\n".join(f"  '{h}'," for h in hashes)
    new_content = f"""/**
 * StockPilot — Full Access PIN Hash Data
 * ------------------------------------------------------------------
 * 50 SHA-256 hashes (with salt) of valid Full Access PINs.
 * Generated by scripts/generate_full_access_pins.py
 *
 * The plaintext PINs are written to download/full_access_pins.txt (gitignored).
 *
 * AUTO-GENERATED — DO NOT EDIT MANUALLY.
 */

export const PIN_SALT = '{salt}';

export const PIN_HASHES: string[] = [
{hash_lines}
];
"""
    with open(PIN_TS, "w") as f:
        f.write(new_content)
    print(f"[OK] Updated {PIN_TS.relative_to(ROOT)} with 50 salted SHA-256 hashes")

if __name__ == "__main__":
    main()
