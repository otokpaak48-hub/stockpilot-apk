#!/usr/bin/env python3
"""
StockPilot — Tier Upgrade Key Generator
=======================================
Generates 50 tier upgrade keys (25 Business + 25 Premium) and:
  1. Writes plaintext keys to download/tier_upgrade_keys.txt (gitignored)
  2. Updates lib/tier-data.ts with SHA-256 hashes + salt + kind

Formats:
  Business: BIZ-XXXX-XXXX
  Premium:  PRM-XXXX-XXXX
"""

import secrets
import hashlib
from pathlib import Path

ROOT     = Path(__file__).resolve().parent.parent
DOWNLOAD = ROOT / "download"
TIER_TS  = ROOT / "lib" / "tier-data.ts"
KEYS_FILE = DOWNLOAD / "tier_upgrade_keys.txt"

CHARS = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"

def gen_key(prefix: str) -> str:
    parts = ["".join(secrets.choice(CHARS) for _ in range(4)) for _ in range(2)]
    return f"{prefix}-" + "-".join(parts)

def gen_salt() -> str:
    return secrets.token_hex(16)

def sha256_with_salt(text: str, salt: str) -> str:
    return hashlib.sha256((salt + text + salt).encode()).hexdigest()

def main():
    DOWNLOAD.mkdir(parents=True, exist_ok=True)

    business = [(gen_key("BIZ"), "business") for _ in range(25)]
    premium  = [(gen_key("PRM"), "premium")  for _ in range(25)]
    all_keys = business + premium

    salt = gen_salt()
    hashes = [{"hash": sha256_with_salt(k, salt), "kind": kind} for k, kind in all_keys]

    with open(KEYS_FILE, "w") as f:
        f.write("# StockPilot — Tier Upgrade Keys (PRIVATE — DO NOT COMMIT)\n")
        f.write("# Generated by scripts/generate_tier_keys.py\n\n")
        f.write("## Business Tier (N2,000/mo)\n")
        for i, (k, _) in enumerate(business, 1):
            f.write(f"{i:2d}. {k}\n")
        f.write("\n## Premium Tier (N5,000/mo)\n")
        for i, (k, _) in enumerate(premium, 1):
            f.write(f"{i:2d}. {k}\n")
    print(f"[OK] Wrote 50 plaintext tier keys → {KEYS_FILE}")
    print(f"     (BACK THIS UP SECURELY — losing it means customers can't upgrade!)")

    hash_lines = "\n".join(f"  {{ hash: '{h['hash']}', kind: '{h['kind']}' }}," for h in hashes)
    new_content = f"""/**
 * StockPilot — Tier Hash Data
 * ------------------------------------------------------------------
 * 25 Business (BIZ-xxx-xxx) + 25 Premium (PRM-xxx-xxx) tier upgrade keys,
 * SHA-256 hashed (with salt).
 *
 * Generated by scripts/generate_tier_keys.py
 * Plaintext keys → download/tier_upgrade_keys.txt (gitignored)
 *
 * AUTO-GENERATED — DO NOT EDIT MANUALLY.
 */

export type TierKeyKind = 'business' | 'premium';

export const TIER_SALT = '{salt}';

export const TIER_HASHES: {{ hash: string; kind: TierKeyKind }}[] = [
{hash_lines}
];
"""
    with open(TIER_TS, "w") as f:
        f.write(new_content)
    print(f"[OK] Updated {TIER_TS.relative_to(ROOT)} with 50 salted SHA-256 hashes")

if __name__ == "__main__":
    main()
