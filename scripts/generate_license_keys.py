#!/usr/bin/env python3
"""
StockPilot — License Key Generator
==================================
Generates 50 license keys in format `SP-XXXX-XXXX-XXXX-XXXX` and:
  1. Writes plaintext keys to download/license_keys.txt  (gitignored — PRIVATE)
  2. Updates lib/license-data.ts with SHA-256 hashes + salt

Usage:
  python3 scripts/generate_license_keys.py
  (or `npm run keys:license`)
"""

import os
import re
import secrets
import hashlib
from pathlib import Path

# Paths
ROOT       = Path(__file__).resolve().parent.parent
DOWNLOAD   = ROOT / "download"
LICENSE_TS = ROOT / "lib" / "license-data.ts"
KEYS_FILE  = DOWNLOAD / "license_keys.txt"

CHARS = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"  # no 0/O/1/I — readability

def gen_key() -> str:
    parts = []
    for _ in range(4):
        parts.append("".join(secrets.choice(CHARS) for _ in range(4)))
    return "SP-" + "-".join(parts)

def gen_salt() -> str:
    return secrets.token_hex(16)

def sha256_with_salt(text: str, salt: str) -> str:
    return hashlib.sha256((salt + text + salt).encode()).hexdigest()

def main():
    DOWNLOAD.mkdir(parents=True, exist_ok=True)

    # Generate 50 keys
    keys = [gen_key() for _ in range(50)]
    salt = gen_salt()
    hashes = [sha256_with_salt(k, salt) for k in keys]

    # 1. Write plaintext keys (PRIVATE — gitignored)
    with open(KEYS_FILE, "w") as f:
        f.write("# StockPilot — License Keys (PRIVATE — DO NOT COMMIT)\n")
        f.write("# Generated by scripts/generate_license_keys.py\n")
        f.write("# Distribute each key to ONE paying customer only.\n\n")
        for i, k in enumerate(keys, 1):
            f.write(f"{i:2d}. {k}\n")
    print(f"[OK] Wrote 50 plaintext license keys → {KEYS_FILE}")
    print(f"     (BACK THIS UP SECURELY — losing it means customers can't activate!)")

    # 2. Update lib/license-data.ts with salt + hashes
    hash_lines = "\n".join(f"  '{h}'," for h in hashes)
    new_content = f"""/**
 * StockPilot — License Hash Data (Layer 1 anti-piracy)
 * ------------------------------------------------------------------
 * 50 SHA-256 hashes (with salt) of valid license keys.
 * Generated by scripts/generate_license_keys.py
 *
 * The plaintext keys are written to download/license_keys.txt (gitignored).
 * Only the hashes + salt are committed — preimage-resistant, so attackers
 * cannot recover the original keys even by reverse-engineering the APK.
 *
 * AUTO-GENERATED — DO NOT EDIT MANUALLY.
 */

export const LICENSE_SALT = '{salt}';

export const LICENSE_HASHES: string[] = [
{hash_lines}
];
"""
    with open(LICENSE_TS, "w") as f:
        f.write(new_content)
    print(f"[OK] Updated {LICENSE_TS.relative_to(ROOT)} with 50 salted SHA-256 hashes")

if __name__ == "__main__":
    main()
